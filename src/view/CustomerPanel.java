    private void loadTable(String keyword) { // Fetches all records from database and populates the table rows
        try { // Attempts the following database operations — errors caught below
            List<Customer> list = (keyword == null || keyword.isEmpty()) // Returns true if the string has no characters
                    ? ctrl.getAllCustomers() : ctrl.searchCustomers(keyword); // Fetches all records from the database for this entity type
            tableModel.setRowCount(0); // Clears all existing rows from the table before reloading fresh data
            for (Customer c : list) { // Loops through each customer record from the database
                tableModel.addRow(new Object[]{ // Adds one data record as a new visible row in the table
                    c.getCustomerId(), c.getFullName(), c.getNicPassport(), // Gets the full display name of this user/customer
                    c.getContactNumber(), c.getEmail(), c.getNationality() // Adds contact number, email and nationality as the last 3 columns of this table row
                }); // Closes the anonymous listener class and the addListener call
            } // Closes this code block (end of method, class, or inner class)
        } catch (SQLException ex) { showError("Failed to load customers."); } // Catches database errors and shows an error message to the user
    } // Closes this code block (end of method, class, or inner class)

    private void populateForm() { // Reads the selected table row and fills all left-side form fields
        int row = tblCustomers.getSelectedRow(); if (row < 0) return; // Gets the index of the selected table row (-1 means no row is selected)
        selectedCustomerId = (int) tableModel.getValueAt(row, 0); // Reads the value from column 0 of the selected table row
        txtId.setText(String.valueOf(selectedCustomerId)); // Sets the display text of this component
        txtName.setText((String) tableModel.getValueAt(row, 1)); // Sets the display text of this component
        txtNic.setText((String) tableModel.getValueAt(row, 2)); // Sets the display text of this component
        txtPhone.setText((String) tableModel.getValueAt(row, 3)); // Sets the display text of this component
        txtEmail.setText(tableModel.getValueAt(row, 4) == null ? "" : (String) tableModel.getValueAt(row, 4)); // Sets the display text of this component
        try { // Attempts the following database operations — errors caught below
            model.Customer c = ctrl.getCustomerById(selectedCustomerId); // Fetches the full Customer record from the database to get address and nationality
            if (c != null) { // Checks for null to prevent NullPointerException
                txtAddress.setText(c.getAddress() == null ? "" : c.getAddress()); // Sets the display text of this component
                txtNationality.setText(c.getNationality() == null ? "" : c.getNationality()); // Sets the display text of this component
            } // Closes this code block (end of method, class, or inner class)
        } catch (SQLException ignored) {} // Catches database errors and shows an error message to the user
    } // Closes this code block (end of method, class, or inner class)

    private void clearForm() { // Resets every form field to blank and deselects any highlighted table row
        selectedCustomerId = -1; // Resets the selected customer ID to -1 (nothing selected)
        txtId.setText(""); txtName.setText(""); txtNic.setText(""); // Sets visible text to: ""
        txtPhone.setText(""); txtEmail.setText(""); // Sets visible text to: ""
        txtAddress.setText(""); txtNationality.setText(""); // Sets visible text to: ""
        tblCustomers.clearSelection(); // Removes any row highlight/selection from the table
    } // Closes this code block (end of method, class, or inner class)

