    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        // TODO add your handling code here:
        if (selectedCustomerId < 0) { showError("Select a customer to delete."); return; } // Checks condition and executes block if true
        if (JOptionPane.showConfirmDialog(this, "Delete this customer?", "Confirm", // Checks condition and executes block if true
                JOptionPane.YES_NO_OPTION) != JOptionPane.YES_OPTION) return; // If user clicked No or closed the dialog, exit without deleting
        try { // Attempts the following database operations — errors caught below
            ctrl.deleteCustomer(selectedCustomerId); // Passes customer ID to controller which deletes from the database
            showSuccess("Customer deleted."); clearForm(); loadTable(null); // Reloads the table with fresh data from the database
        } catch (SQLException ex) { showError("Cannot delete – customer may have linked bookings."); } // Catches database errors and shows an error message to the user
    

    }//GEN-LAST:event_btnDeleteActionPerformed

