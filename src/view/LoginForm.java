    private void btnShowHideActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnShowHideActionPerformed
        // TODO add your handling code here:
        passwordVisible = !passwordVisible; // Flip the visible flag (true → false, false → true)

        if (passwordVisible) { // Checks current password visibility state
            // Password is now visible: show actual characters
            txtPassword.setEchoChar((char) 0); // 0 means "no masking character" = show real text
            btnShowHide.setText("Hide");        // Change button label to "Hide"
        } else { // Runs this block when none of the above conditions were true
            // Password is now hidden: show dots again
            txtPassword.setEchoChar('\u2022'); // • bullet character used as the masking dot
            btnShowHide.setText("Show");       // Change button label back to "Show"
        } // Closes this code block (end of method, class, or inner class)
    }//GEN-LAST:event_btnShowHideActionPerformed

