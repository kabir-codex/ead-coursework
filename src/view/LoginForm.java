    private void doLogin() { // Reads username/password/role, authenticates via UserDAO, opens MainFrame on success
        String username = txtUsername.getText().trim();                    // Get username, remove extra spaces
        String password = new String(txtPassword.getPassword()).trim();    // Get password text, remove spaces
        String role     = (String) cmbRole.getSelectedItem();             // Get chosen role (ADMIN/RECEPTIONIST)

        // Check that neither field was left empty
        if (username.isEmpty() || password.isEmpty()) { // Checks if the input field is empty — stops execution if nothing was typed
            lblError.setText("Please enter username and password."); // Show error in red
            return; // Stop here – do not try to connect to the database
        } // Closes this code block (end of method, class, or inner class)

        try { // Attempts the following database operations — errors caught below
            // Ask the UserDAO to look up these credentials in the database
            User user = userDAO.authenticate(username, password); // Declares User model variable "user"

            // Check: did we find a user AND does their role match what was selected?
            if (user != null && user.getRole().name().equals(role)) { // Checks for null to prevent NullPointerException
                // ✅ Login successful!
                dispose(); // Close the login window
                javax.swing.SwingUtilities.invokeLater(() -> { // Schedules code to run on the Swing Event Dispatch Thread (prevents UI freezes)
                    // Open the main application window on the UI thread
                    new MainFrame(user).setVisible(true); // Makes this window or component appear on screen
                }); // Closes the anonymous listener class and the addListener call
            } else { // Runs this block when none of the above conditions were true
                // ❌ Wrong username, password, or role
                lblError.setText("Invalid credentials or role mismatch."); // Show error in red
                txtPassword.setText(""); // Clear the password field for security
            } // Closes this code block (end of method, class, or inner class)
        } catch (SQLException ex) { // Catches database errors and shows an error message to the user
            // Something went wrong connecting to the database
            lblError.setText("Database error: " + ex.getMessage()); // Show the database error
        } // Closes this code block (end of method, class, or inner class)
    } // Closes this code block (end of method, class, or inner class)

