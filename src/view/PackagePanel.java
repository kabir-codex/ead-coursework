     private void loadTable(String keyword) { // Fetches all records from database and populates the table rows
        try { // Attempts the following database operations — errors caught below
            List<Package> list = (keyword==null||keyword.isEmpty()) ? ctrl.getAllPackages() : ctrl.searchPackages(keyword); // Returns true if the string has no characters
            tableModel.setRowCount(0); // Clears all existing rows from the table before reloading fresh data
            for (Package p : list) tableModel.addRow(new Object[]{p.getPackageId(),p.getPackageName(),p.getDestination(),p.getDurationDays(),String.format("%.2f",p.getPrice()),p.getStatus()}); // Adds one data record as a new visible row in the table
        } catch (SQLException ex) { JOptionPane.showMessageDialog(this,"Failed to load.","Error",JOptionPane.ERROR_MESSAGE); } // Catches database errors and shows an error message to the user
    } // Closes this code block (end of method, class, or inner class)
    private void populateForm() { // Reads the selected table row and fills all left-side form fields
        int row=tblPackages.getSelectedRow(); if(row<0) return; // Gets the index of the selected table row (-1 means no row is selected)
        selectedId=(int)tableModel.getValueAt(row,0); // Reads the value from column 0 of the selected table row
        txtId.setText(String.valueOf(selectedId)); txtName.setText((String)tableModel.getValueAt(row,1)); // Sets the display text of this component
        txtDest.setText((String)tableModel.getValueAt(row,2)); txtDuration.setText(String.valueOf(tableModel.getValueAt(row,3))); // Sets the display text of this component
        txtPrice.setText(String.valueOf(tableModel.getValueAt(row,4))); cmbStatus.setSelectedItem(String.valueOf(tableModel.getValueAt(row,5))); // Sets the display text of this component
        try { Package p=ctrl.getPackageById(selectedId); if(p!=null) txtDesc.setText(p.getDescription()); } catch(SQLException ignored){} // Sets the display text of this component
    } // Closes this code block (end of method, class, or inner class)
    private void clearForm() { // Resets every form field to blank and deselects any highlighted table row
        selectedId=-1; txtId.setText(""); txtName.setText(""); txtDest.setText(""); txtDuration.setText(""); txtPrice.setText(""); txtDesc.setText(""); cmbStatus.setSelectedIndex(0); tblPackages.clearSelection(); // Sets visible text to: ""
    } // Closes this code block (end of method, class, or inner class)
