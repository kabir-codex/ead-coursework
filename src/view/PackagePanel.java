    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        // TODO add your handling code here:
         if (selectedId<0){JOptionPane.showMessageDialog(this,"Select a package.","Error",JOptionPane.ERROR_MESSAGE);return;} // Checks a valid record is selected before attempting an operation
        try { // Attempts the following database operations — errors caught below
            ctrl.updatePackage(selectedId, txtName.getText(), txtDest.getText(), txtDuration.getText(), txtPrice.getText(), txtDesc.getText(), Package.Status.valueOf((String)cmbStatus.getSelectedItem())); // Gets the currently selected item from the dropdown as an Object
            JOptionPane.showMessageDialog(this,"Package updated.","Success",JOptionPane.INFORMATION_MESSAGE); loadTable(null); // Shows a pop-up dialog box with the specified message and title
        } catch (InvalidBookingException|SQLException ex) { JOptionPane.showMessageDialog(this,ex.getMessage(),"Error",JOptionPane.ERROR_MESSAGE); } // Catches validation failures from the controller layer
    
    }//GEN-LAST:event_btnUpdateActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        // TODO add your handling code here:
        if (selectedId<0){JOptionPane.showMessageDialog(this,"Select a package.","Error",JOptionPane.ERROR_MESSAGE);return;} // Checks a valid record is selected before attempting an operation
        if (JOptionPane.showConfirmDialog(this,"Delete this package?","Confirm",JOptionPane.YES_NO_OPTION)!=JOptionPane.YES_OPTION) return; // Proceeds only if user clicked Yes in the confirmation dialog
        try { ctrl.deletePackage(selectedId); JOptionPane.showMessageDialog(this,"Deleted.","Success",JOptionPane.INFORMATION_MESSAGE); clearForm(); loadTable(null); } // Starts a try block — errors thrown here are caught in the catch block
        catch (SQLException ex) { JOptionPane.showMessageDialog(this,"Cannot delete – linked to bookings.","Error",JOptionPane.ERROR_MESSAGE); } // Shows a pop-up dialog box with the specified message and title
    
    }//GEN-LAST:event_btnDeleteActionPerformed

